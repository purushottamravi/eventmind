CREATE TABLE DOMAIN_EVENT_ENTRY
(
    GLOBAL_INDEX         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    EVENT_IDENTIFIER     VARCHAR(255) NOT NULL,
    AGGREGATE_IDENTIFIER VARCHAR(255) NOT NULL,
    SEQUENCE_NUMBER      BIGINT       NOT NULL,
    TYPE                 VARCHAR(255),
    TIME_STAMP           VARCHAR(255),
    PAYLOAD_TYPE         VARCHAR(255) NOT NULL,
    PAYLOAD              BLOB         NOT NULL,
    META_DATA            BLOB,
    PAYLOAD_REVISION     VARCHAR(255),
    PRIMARY KEY (GLOBAL_INDEX)
);

CREATE TABLE SNAPSHOT_EVENT_ENTRY
(
    AGGREGATE_IDENTIFIER VARCHAR(255) NOT NULL,
    SEQUENCE_NUMBER      BIGINT       NOT NULL,
    TYPE                 VARCHAR(255),
    EVENT_IDENTIFIER     VARCHAR(255) NOT NULL,
    TIMESTAMP            TIMESTAMP    NOT NULL,
    PAYLOAD_TYPE         VARCHAR(255) NOT NULL,
    PAYLOAD              BLOB         NOT NULL,
    META_DATA            BLOB,
    PAYLOAD_REVISION     VARCHAR(255),
    TIME_STAMP     VARCHAR(255),
    PRIMARY KEY (AGGREGATE_IDENTIFIER, SEQUENCE_NUMBER, TYPE)
);

CREATE TABLE ASSOCIATION_VALUE_ENTRY
(
    ID                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ASSOCIATION_KEY   VARCHAR(255),
    ASSOCIATION_VALUE VARCHAR(255),
    SAGA_ID           VARCHAR(255),
    SAGA_TYPE         VARCHAR(255),
    PRIMARY KEY (ID)
);

CREATE TABLE TOKEN_ENTRY
(
    PROCESSOR_NAME VARCHAR(255) NOT NULL,
    SEGMENT        INTEGER      NOT NULL,
    TOKEN          BLOB,
    TOKEN_TYPE     VARCHAR(255),
    TIMESTAMP      VARCHAR(255),
    OWNER          VARCHAR(255),
    PRIMARY KEY (PROCESSOR_NAME, SEGMENT)
);


CREATE TABLE DEAD_LETTER_ENTRY
(
    DEAD_LETTER_ID       VARCHAR(255) PRIMARY KEY,
    PROCESSING_GROUP     VARCHAR(255) NOT NULL,
    SEQUENCE_IDENTIFIER  VARCHAR(255),
    SEQUENCE_INDEX       BIGINT,
    MESSAGE_TYPE         VARCHAR(255),
    EVENT_IDENTIFIER     VARCHAR(255),
    AGGREGATE_IDENTIFIER VARCHAR(255),
    PAYLOAD_TYPE         VARCHAR(255),
    PAYLOAD              BLOB,
    META_DATA            BLOB,
    DIAGNOSTICS          BLOB,
    CAUSE_TYPE           VARCHAR(255),
    CAUSE_MESSAGE        VARCHAR(1023),
    ENQUEUED_AT          TIMESTAMP,
    LAST_TOUCHED         TIMESTAMP,
    SEQUENCE_NUMBER      BIGINT,
    TIME_STAMP           VARCHAR(255),
    TOKEN                BLOB,
    TOKEN_TYPE           VARCHAR(255),
    TYPE                 VARCHAR(255),
    PROCESSING_STARTED   TIMESTAMP,
    PAYLOAD_REVISION     VARCHAR(255)

);

CREATE TABLE SAGA_ENTRY
(
    SAGA_ID         VARCHAR(255),
    SAGA_TYPE       VARCHAR(255),
    REVISION        VARCHAR(255),
    SERIALIZED_SAGA  BLOB,
    PRIMARY KEY (SAGA_ID)
);

CREATE SEQUENCE ASSOCIATION_VALUE_ENTRY_SEQ START WITH 1  INCREMENT BY 50;
